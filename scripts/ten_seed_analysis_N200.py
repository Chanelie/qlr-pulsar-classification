#!/usr/bin/env python3
"""
Ten-seed analysis at N=200, L=3 on the fixed split (DATA_SEED=42).

Inputs (read-only), seeds 0-9:
  caches/N200_enc-angle_q8_L3_E60_seed{s}.pkl       QLR-angle, seeds 0-9
  caches/baselines_N200_seed{s}.pkl                 weighted LogReg/CSVM/XGBoost + QSVM (grid job)
  results/calibrated_baselines_train/preds_N200_seed{s}.pkl
                                                    unweighted and calibrated baselines
                                                    (weighted/none is checked bit-identical to the cache)
Outputs:
  tables/ten_seed_N200_L3.csv   (sections: per_seed, summary, delta_per_seed, delta_summary)
  TEN_SEED_SUMMARY.md
"""
from __future__ import annotations

import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from paired_seed_stats import all_metrics, analyse, md_tables, KEY_METRICS   # noqa: E402

SEEDS = list(range(10))
REF = "QLR-angle"
NAME = {"LogReg": "LogReg", "CSVM": "SVM-RBF", "XGBoost": "XGBoost"}


def main() -> int:
    rows, y_ref = [], None
    for s in SEEDS:
        q = pickle.load(open(ROOT / "caches" / f"N200_enc-angle_q8_L3_E60_seed{s}.pkl", "rb"))
        y = np.asarray(q["y_test"]); y_ref = y if y_ref is None else y_ref
        assert np.array_equal(y, y_ref), "test split differs"
        rows.append(dict(model=REF, seed=s, **all_metrics(y, list(q["probs"].values())[0])))
        bl = pickle.load(open(ROOT / "caches" / f"baselines_N200_seed{s}.pkl", "rb"))
        assert np.array_equal(bl["y_true"], y)
        rows.append(dict(model="QSVM (weighted)", seed=s, **all_metrics(y, bl["probs"]["QSVM"])))
        pb = pickle.load(open(ROOT / "results" / "calibrated_baselines_train" / f"preds_N200_seed{s}.pkl", "rb"))
        assert np.array_equal(pb["y_test"], y)
        for (m, w, meth), p in pb["probs"].items():
            if w == "weighted" and meth == "none":
                assert np.array_equal(p, np.asarray(bl["probs"][m], float)), f"calibration input != baseline cache {m} s{s}"
            label = f"{NAME[m]} {w}" + ("" if meth == "none" else f" + {'Platt' if meth == 'sigmoid' else 'isotonic'}")
            rows.append(dict(model=label, seed=s, **all_metrics(y, p)))
    per = pd.DataFrame(rows)
    summ, dper, dsum = analyse(per, REF)

    # Also report the main grid's three-seed subset for comparison with tables/qlr_mean_N200_L3.csv.
    sub3 = per[(per.model == REF) & (per.seed <= 2)]
    three = pd.DataFrame([dict(model=f"{REF} (seeds 0-2 only)", metric=k, n_seeds=3, mean=sub3[k].mean(),
                               se=sub3[k].std(ddof=1) / np.sqrt(3)) for k in KEY_METRICS])

    out = pd.concat([per.assign(section="per_seed"),
                     pd.concat([summ, three]).assign(section="summary"),
                     dper.assign(section="delta_per_seed"),
                     dsum.assign(section="delta_summary")], ignore_index=True)
    cols = ["section"] + [c for c in out.columns if c != "section"]
    out[cols].to_csv(ROOT / "tables" / "ten_seed_N200_L3.csv", index=False)

    order = [REF, "LogReg weighted", "LogReg unweighted", "SVM-RBF weighted", "SVM-RBF unweighted",
             "XGBoost weighted", "XGBoost unweighted",
             "LogReg weighted + Platt", "LogReg weighted + isotonic", "LogReg unweighted + Platt",
             "LogReg unweighted + isotonic", "SVM-RBF weighted + Platt", "SVM-RBF weighted + isotonic",
             "SVM-RBF unweighted + Platt", "SVM-RBF unweighted + isotonic", "XGBoost weighted + Platt",
             "XGBoost weighted + isotonic", "XGBoost unweighted + Platt", "XGBoost unweighted + isotonic",
             "QSVM (weighted)"]
    md = ["# Ten-seed analysis — N = 200, L = 3, fixed split (DATA_SEED = 42)", "",
          "Generated by `scripts/ten_seed_analysis_N200.py`; full numbers (all metrics, per-seed values) in "
          "`tables/ten_seed_N200_L3.csv`. Seeds 0–9 use the fixed test split. Weighted baselines and QSVM "
          "are read from the main baseline caches; unweighted and calibrated baselines use "
          "`CalibratedClassifierCV(cv=5)` fitted on the training subset only. Values are reported as "
          "mean ± SE over n = 10 seeds.", "",
          "With n = 10 pairs the smallest attainable exact two-sided Wilcoxon p-value is 0.00195. "
          "Holm adjustment is applied within each metric across the 19 comparators.", "",
          md_tables(summ, dsum, REF, order), ""]
    summary_path = ROOT / "docs" / "TEN_SEED_SUMMARY.md"
    summary_path.write_text("\n".join(md))
    print(f"[ten-seed] wrote tables/ten_seed_N200_L3.csv and {summary_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
