#!/usr/bin/env python3
"""
Write the bootstrap summary from tables/bootstrap_intervals.csv
(produced by scripts/bootstrap_test_set.py). No computation beyond formatting.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
KEY = ["PR_AUC", "ROC_AUC", "Recall_FPR1", "Recall_FPR5", "Brier", "ECE"]
LOWER = {"Brier", "ECE"}
ORDER = ["LogReg|unweighted|none", "LogReg|weighted|none", "CSVM|unweighted|none", "CSVM|weighted|none",
         "XGBoost|unweighted|none", "XGBoost|weighted|none",
         "LogReg|unweighted|sigmoid", "LogReg|unweighted|isotonic", "LogReg|weighted|sigmoid",
         "LogReg|weighted|isotonic", "CSVM|unweighted|sigmoid", "CSVM|unweighted|isotonic",
         "CSVM|weighted|sigmoid", "CSVM|weighted|isotonic", "XGBoost|unweighted|sigmoid",
         "XGBoost|unweighted|isotonic", "XGBoost|weighted|sigmoid", "XGBoost|weighted|isotonic",
         "QSVM|weighted|none"]


def label(c: str) -> str:
    if c.startswith("QLR-"):
        return c.replace("data_reuploading", "DR")
    m, w, k = c.split("|")
    m = {"CSVM": "SVM-RBF"}.get(m, m)
    return f"{m} {w}" + {"none": "", "sigmoid": " + Platt", "isotonic": " + isotonic"}[k]


def fmt(r, d=4):
    return f"{r.point:.{d}f} [{r.lo:.{d}f}, {r.hi:.{d}f}]"


def fmt_delta(r, metric, d=4):
    s = f"{r.point:+.{d}f} [{r.lo:+.{d}f}, {r.hi:+.{d}f}]"
    excl = (r.lo > 0) or (r.hi < 0)
    if excl:
        better = (r.hi < 0) if metric in LOWER else (r.lo > 0)
        s = f"**{s}** {'Q' if better else 'C'}"
    return s


def main() -> int:
    df = pd.read_csv(ROOT / "tables" / "bootstrap_intervals.csv")
    scopes = sorted(s for s in df.scope.unique() if s.startswith("pooled"))
    L = ["# Paired bootstrap of the fixed test set", "",
         "Generated by `scripts/bootstrap_test_set.py` (computation) and `scripts/bootstrap_summary.py` "
         "(this file). Full results: `tables/bootstrap_intervals.csv` — per-seed and pooled intervals for "
         "every (N, L, encoding) and every comparator.", "",
         "**Method.** Test set = the main experiment's fixed split (3580 points, 328 pulsars). For each seed, "
         "B = 2000 class-stratified resamples with replacement; the same resample indices are applied to QLR "
         "and every comparator of that seed (paired), independent indices for different seeds. Metrics use the "
         "repository implementations (`average_precision_score`, `roc_auc_score`, `metrics_at_fpr`, `brier_score_loss`, "
         "15-bin equal-mass `ece_from_probs`). Intervals are 2.5–97.5 % percentiles. **Pooled** = replicates "
         "of all listed seeds concatenated (e.g. 3 × 2000); the point value is the mean of the per-seed "
         "full-test-set values, so pooled intervals include seed-to-seed (training) variability as well as "
         "test-set sampling variability. Comparators include weighted and unweighted baselines, "
         "training-fold-calibrated baselines (Platt = `sigmoid`, isotonic), and QSVM.", "",
         "Δ = QLR − comparator. Bold = the 95 % interval excludes 0; **Q** = QLR better, **C** = comparator "
         "better (for Brier and ECE, negative Δ = QLR better).", ""]

    for scope in scopes:
        for n in (1000, 200):
            sub = df[(df.scope == scope) & (df.N == n)]
            if sub.empty or not (pd.to_numeric(sub.L, errors="coerce") == 3).any():
                continue
            encs = sorted(sub[(sub.kind == "value") & (pd.to_numeric(sub.L, errors="coerce") == 3)].encoding.dropna().unique())
            if not encs:
                continue
            L.append(f"## N = {n}, L = 3 — {scope.replace('_', ' seeds ')}")
            L.append("")
            vals = sub[sub.kind == "value"]
            L.append("### Values (point [95 % interval])")
            L.append("")
            L.append("| Model | " + " | ".join(KEY) + " |")
            L.append("|---|" + "---|" * len(KEY))
            models = [f"QLR-{e}-L3" for e in ["angle", "data_reuploading", "amplitude"] if e in encs] + \
                     [c for c in ORDER if c in set(vals.model)]
            for m in models:
                r = vals[vals.model == m].set_index("metric")
                if r.empty:
                    continue
                L.append(f"| {label(m)} | " + " | ".join(fmt(r.loc[k]) for k in KEY) + " |")
            L.append("")
            for e in ["angle", "data_reuploading", "amplitude"]:
                d = sub[(sub.kind == "delta") & (sub.encoding == e) & (pd.to_numeric(sub.L, errors="coerce") == 3)]
                if d.empty:
                    continue
                L.append(f"### Δ = {label('QLR-' + e)} − comparator")
                L.append("")
                L.append("| Comparator | " + " | ".join(KEY) + " |")
                L.append("|---|" + "---|" * len(KEY))
                for c in [c for c in ORDER if c in set(d.model)]:
                    r = d[d.model == c].set_index("metric")
                    L.append(f"| {label(c)} | " + " | ".join(fmt_delta(r.loc[k], k) for k in KEY) + " |")
                L.append("")

    # grid-wide count: per-seed Δ intervals for QLR-angle vs unweighted LogReg
    d = df[(df.kind == "delta") & (df.scope == "seed") & (df.encoding == "angle") &
           (df.model == "LogReg|unweighted|none")]
    if not d.empty:
        L.append("## Across the whole grid: per-seed intervals, QLR-angle vs unweighted LogReg")
        L.append("")
        L.append("Number of (N, L, seed) cells whose 95 % Δ interval excludes 0, by direction "
                 f"(total cells per metric: {d.groupby('metric').size().iloc[0]}).")
        L.append("")
        L.append("| Metric | QLR better | LogReg better | interval contains 0 |")
        L.append("|---|---|---|---|")
        for k in KEY:
            x = d[d.metric == k]
            qb = ((x.hi < 0) if k in LOWER else (x.lo > 0)).sum()
            cb = ((x.lo > 0) if k in LOWER else (x.hi < 0)).sum()
            L.append(f"| {k} | {qb} | {cb} | {len(x) - qb - cb} |")
        L.append("")
    out = ROOT / "docs" / "BOOTSTRAP_SUMMARY.md"
    out.write_text("\n".join(L))
    print(f"[bootstrap] wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
