#!/usr/bin/env python3
"""
Split-robustness analysis at N=200, L=3.

Each seed s uses its OWN stratified 80/20 split (random_state = s; scaler fitted
on that training split), produced by scripts/run_split_robustness.py.
Inputs (read-only), seeds 0-9:
  caches_split_robustness/splitN200_enc-angle_q8_L3_E60_seed{s}.pkl   QLR-angle
  caches_split_robustness/baselines_N200_seed{s}.pkl                  weighted LogReg/CSVM/XGBoost (+QSVM)
                                                                      and unweighted LogReg/CSVM/XGBoost
Outputs:
  tables/split_robustness_N200_L3.csv   (sections: per_seed, summary, delta_per_seed, delta_summary)
  SPLIT_ROBUSTNESS_SUMMARY.md
"""
from __future__ import annotations

import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from paired_seed_stats import all_metrics, analyse, md_tables   # noqa: E402

SEEDS = list(range(10))
REF = "QLR-angle"
NAME = {"LogReg": "LogReg", "CSVM": "SVM-RBF", "XGBoost": "XGBoost"}
D = ROOT / "caches_split_robustness"


def main() -> int:
    rows = []
    for s in SEEDS:
        q = pickle.load(open(D / f"splitN200_enc-angle_q8_L3_E60_seed{s}.pkl", "rb"))
        bl = pickle.load(open(D / f"baselines_N200_seed{s}.pkl", "rb"))
        y = np.asarray(q["y_test"])
        assert np.array_equal(y, bl["y_true"]), f"QLR and baselines use different test sets at seed {s}"
        assert np.array_equal(np.asarray(q["subset_idx"]), np.asarray(bl["subset_idx"])), "subset differs"
        rows.append(dict(model=REF, seed=s, **all_metrics(y, list(q["probs"].values())[0])))
        for m in ["LogReg", "CSVM", "XGBoost"]:
            rows.append(dict(model=f"{NAME[m]} weighted", seed=s, **all_metrics(y, bl["probs_weighted"][m])))
            rows.append(dict(model=f"{NAME[m]} unweighted", seed=s, **all_metrics(y, bl["probs_unweighted"][m])))
        rows.append(dict(model="QSVM (weighted)", seed=s, **all_metrics(y, bl["probs_weighted"]["QSVM"])))
    per = pd.DataFrame(rows)
    summ, dper, dsum = analyse(per, REF)
    out = pd.concat([per.assign(section="per_seed"), summ.assign(section="summary"),
                     dper.assign(section="delta_per_seed"), dsum.assign(section="delta_summary")],
                    ignore_index=True)
    cols = ["section"] + [c for c in out.columns if c != "section"]
    out[cols].to_csv(ROOT / "tables" / "split_robustness_N200_L3.csv", index=False)

    order = [REF, "LogReg weighted", "LogReg unweighted", "SVM-RBF weighted", "SVM-RBF unweighted",
             "XGBoost weighted", "XGBoost unweighted", "QSVM (weighted)"]
    md = ["# Split-robustness analysis — N = 200, L = 3, one stratified 80/20 split per seed", "",
          "Generated by `scripts/split_robustness_analysis.py`; all metrics and per-seed values in "
          "`tables/split_robustness_N200_L3.csv`. Seed s draws its train/test split with `random_state = s` "
          "(the grid uses 42 for every seed) and fits the scaler on that training split; everything else is "
          "identical to the grid (`scripts/run_split_robustness.py`). Seeds 0–9, n = 10, mean ± SE. Each seed "
          "has a different test set, so the SEs include test-set sampling variability.", "",
          "Smallest attainable exact two-sided Wilcoxon p with 10 pairs: 0.00195. Holm adjustment within each "
          "metric across the 7 comparators.", "",
          md_tables(summ, dsum, REF, order), ""]
    summary_path = ROOT / "docs" / "SPLIT_ROBUSTNESS_SUMMARY.md"
    summary_path.write_text("\n".join(md))
    print(f"[split robustness] wrote tables/split_robustness_N200_L3.csv and {summary_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
